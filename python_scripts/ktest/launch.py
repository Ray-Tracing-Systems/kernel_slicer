"""Generation of VS Code debug configurations (launch.json) for selected (usually failed) runs."""
import os
import json
import time

IS_WINDOWS = os.name == 'nt'
MARKER     = '// generated by ktest.py'


def _ws(path, root):
    rel = os.path.relpath(path, root).replace(os.sep, '/')
    return path.replace(os.sep, '/') if rel.startswith('..') else '${workspaceFolder}/' + rel


def make_config(run, root, program):
    args = [_ws(a, root) if os.path.isabs(a) else a for a in run.kslicer_args()]
    cfg = {
        'name':    f'Launch ({run.full_name})',
        'type':    'cppvsdbg' if IS_WINDOWS else 'cppdbg',
        'request': 'launch',
        'program': program,
        'args':    args,
        'stopAtEntry': False,
        'cwd':     '${workspaceFolder}',
        'environment': [],
    }
    if IS_WINDOWS:
        cfg['console'] = 'integratedTerminal'
    else:
        cfg['externalConsole'] = False
        cfg['MIMode'] = 'gdb'
        cfg['setupCommands'] = [{'description': 'Enable pretty-printing for gdb',
                                 'text': '-enable-pretty-printing', 'ignoreFailures': True}]
    return cfg


def write_launch(runs, root, path, program=None):
    if program is None:
        program = '${workspaceFolder}/cmake-build-debug/kslicer' + ('.exe' if IS_WINDOWS else '')
    data = {'version': '0.2.0', 'configurations': [make_config(r, root, program) for r in runs]}
    if os.path.isfile(path):  # never lose user's launch.json: keep it unless it was written by ktest
        with open(path, encoding='utf-8', errors='replace') as f:
            generated = f.readline().startswith(MARKER)
        if not generated:
            os.replace(path, path + '.' + time.strftime('%Y%m%d_%H%M%S') + '.bak')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(MARKER + '\n')
        json.dump(data, f, indent=4)
        f.write('\n')
