#!/usr/bin/env python3
"""
Register pressure of ISPC kernels generated by kernel_slicer, from the assembly of the ISPC compiler.

A CPU core has no occupancy limit like a GPU: when a kernel needs more vector registers than the target has
(16 ymm registers for AVX2), the compiler spills values to the stack. LLVM marks such instructions in the assembly
with comments '# 32-byte Spill', '# 32-byte Reload' and '# 32-byte Folded Reload'. For every exported kernel
('<Name>_ISPC', except '_Bind_ISPC') the script counts these instructions in the kernel and in all functions it calls
(static counts, like the Spill/Fill counts of Intel ANV), and reports the largest stack frame among them.

  python3 ispc_spills.py <z_build_ispc.sh> [--json out.json] [--keep-asm out.s]

The ISPC command line is taken from z_build_ispc.sh generated by kernel_slicer, the object file is replaced by assembly.
"""
import argparse
import json
import re
import shlex
import subprocess
import tempfile
from pathlib import Path


def ispc_command(script):
    for line in Path(script).read_text().splitlines():
        if line.strip().startswith("ispc "):
            return shlex.split(line.replace("$EMBREE4_FLAGS", ""))
    raise RuntimeError(f"no 'ispc' command in {script}")


def compile_asm(script, asm_path):
    cmd = ispc_command(script)
    out, skip = [], False
    for a in cmd:
        if skip:
            skip = False
            continue
        if a in ("-o", "-h"):   # object file and header are not needed
            skip = True
            continue
        if a.endswith(".ispc") and not Path(a).exists() and (Path(script).parent / Path(a).name).exists():
            a = str(Path(script).parent / Path(a).name)   # moved to the folder of the script (HydraCore3/ispc_build.sh)
        out.append(a)
    out += ["--emit-asm", "-o", str(asm_path)]
    res = subprocess.run(out, cwd=Path(script).parent, capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError("ispc failed:\n" + res.stdout + res.stderr)


def parse_asm(asm_path):
    """function name ==> {'spills', 'reloads', 'frame', 'calls'}"""
    funcs, cur = {}, None
    label = re.compile(r"^([A-Za-z_.$][\w.$@]*):")
    for line in Path(asm_path).read_text().splitlines():
        m = label.match(line)
        if m and not m.group(1).startswith(".L"):
            cur = funcs.setdefault(m.group(1), {"spills": 0, "reloads": 0, "frame": 0, "calls": set()})
            continue
        if cur is None:
            continue
        if "Spill" in line:
            cur["spills"] += 1
        elif "Reload" in line:       # 'Reload' and 'Folded Reload'
            cur["reloads"] += 1
        m = re.search(r"\bsub[q]?\s+\$(\d+),\s*%rsp", line)
        if m:
            cur["frame"] = max(cur["frame"], int(m.group(1)))
        m = re.search(r"\bcall[q]?\s+([A-Za-z_.$][\w.$@]*)", line)
        if m:
            cur["calls"].add(m.group(1).split("@")[0])
    return funcs


def kernel_stats(funcs):
    res = {}
    for name in funcs:
        if not name.endswith("_ISPC") or name.endswith("_Bind_ISPC"):
            continue
        seen, stack = set(), [name]
        while stack:
            f = stack.pop()
            if f in seen or f not in funcs:
                continue
            seen.add(f)
            stack += list(funcs[f]["calls"])
        res[name] = {"spills":    sum(funcs[f]["spills"] for f in seen),
                     "reloads":   sum(funcs[f]["reloads"] for f in seen),
                     "frame":     max(funcs[f]["frame"] for f in seen),
                     "functions": len(seen)}
    return res


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("script", help="z_build_ispc.sh generated by kernel_slicer")
    ap.add_argument("--json", help="write results to this file")
    ap.add_argument("--keep-asm", help="keep assembly in this file")
    args = ap.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        asm = Path(args.keep_asm) if args.keep_asm else Path(tmp) / "kernels.s"
        compile_asm(Path(args.script).resolve(), asm.resolve())
        stats = kernel_stats(parse_asm(asm))
    print(f"{'kernel':40s} {'spills':>7s} {'reloads':>8s} {'frame,B':>8s} {'funcs':>6s}")
    for name, s in sorted(stats.items()):
        print(f"{name:40s} {s['spills']:7d} {s['reloads']:8d} {s['frame']:8d} {s['functions']:6d}")
    if args.json:
        Path(args.json).write_text(json.dumps(stats, indent=2) + "\n")


if __name__ == "__main__":
    main()
