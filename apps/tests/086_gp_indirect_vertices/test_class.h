#pragma once
#include <vector>
#include <cstdint>

#include "LiteMath.h"
#include "Image2d.h"
#include "raster.h"

using LiteMath::float4;
using LiteMath::int2;
using LiteMath::clamp;
using LiteImage::Image2D;

struct ColorVaryings  // vertex shader output, pixel shader input
{
  float4 color;
};

struct GenTriangle    // triangle generated by kernel1D_MakeTriangles, clip space positions
{
  float4 p0;
  float4 p1;
  float4 p2;
  float4 color;
};

/**
\brief Indirect non indexed draws: vertex counts are expressions of data of the class, so they are computed on GPU.
         * kernel1D_MakeTriangles generates an unknown number of triangles with push_back, they are drawn with
           '3*uint32_t(m_tris.size())' vertices;
         * the depth only pass before it draws '3*m_holeNum' vertices: m_holeNum is a POD member set on host, it is read
           from class data on GPU as well.
       Two frames with different numbers of triangles are put side by side.
*/
class IndirectTriangles
{
public:
  IndirectTriangles() {}
  virtual ~IndirectTriangles() {}

  static constexpr uint32_t GRID = 32; ///< GRID x GRID cells, at most one triangle in every cell

  void SetViewport(int a_width, int a_height); ///< host only: images, pipeline state and geometry

  virtual void Render(int a_width, int a_height, uint32_t a_frame, uint32_t* a_out [[size("a_width*a_height")]]);

  virtual void CommitDeviceData() {}
  virtual void GetExecutionTime(const char* a_funcName, float a_out[4]);

protected:

  virtual void kernel1D_MakeTriangles(uint32_t a_cellNum, uint32_t a_frame);  ///< some cells --> m_tris
  float4 kernelVS_Tri(uint32_t a_vertId, ColorVaryings* a_out) const;
  float4 kernelVS_Hole(uint32_t a_vertId) const;                            ///< depth only pass
  float4 kernelPS_Color(const ColorVaryings& a_in) const;
  virtual void kernel2D_ToOutput(int a_width, int a_height, uint32_t* a_out);

  std::vector<GenTriangle> m_tris;       ///< written by kernel1D_MakeTriangles
  std::vector<float4>      m_holeVerts;  ///< triangles of the depth only pass
  uint32_t                 m_holeNum = 0;

  Image2D<float4>          m_color;
  Image2D<float>           m_depth;
  LiteRS::Pipeline         m_pipeline;
  float                    m_timeRender = 0.0f;
};
